// ── 집계 해석 기사용 통계 (빌드 시 실데이터에서 계산 — 하드코딩 금지) ──────────
// 모집단: 취업률 공시 보유 + 비원격 + 모집중 (model.js의 isMeaningful과 동일 기준)
// 여기서 만든 수치는 매일 05:50 KST 빌드 때 자동으로 최신화된다.
function analysis(M) {
  const W = M.courses.filter(c => c.emplRate != null && !c.remote && c.status === '모집중');
  const avg = a => a.length ? a.reduce((s, x) => s + x, 0) / a.length : null;
  const pct = (a, p) => { const b = [...a].sort((x, y) => x - y); return b[Math.floor(b.length * p)]; };
  const r1 = n => n == null ? '-' : n.toFixed(1);
  // "14일, 총56시간" → 56
  const hoursOf = c => { const m = (c.hours || '').match(/총\s*([\d,]+)\s*시간/); return m ? +m[1].replace(/,/g, '') : null; };
  const catName = slug => (M.cats.find(c => c.slug === slug) || {}).name || slug;
  // 분야명이 데이터에서 오므로 조사를 하드코딩하면 "IT·개발는"처럼 깨진다 → 받침 판정으로 붙인다.
  // 마지막 글자가 한글이 아니면(영문·기호로 끝나는 "AI·데이터" 등) 앞으로 훑어 마지막 한글을 찾는다.
  const hasBatchim = word => {
    for (let i = (word || '').length - 1; i >= 0; i--) {
      const code = word.charCodeAt(i);
      if (code >= 0xac00 && code <= 0xd7a3) return (code - 0xac00) % 28 !== 0;
    }
    return false; // 한글이 없으면 받침 없음으로 취급
  };
  const josa = (word, withB, withoutB) => `${word}${hasBatchim(word) ? withB : withoutB}`;
  const eun = w => josa(w, '은', '는');
  const gwa = w => josa(w, '과', '와');

  // ① 훈련시간 구간별
  const hourBins = [[0, 99, '100시간 미만'], [100, 199, '100~199시간'], [200, 499, '200~499시간'], [500, 799, '500~799시간'], [800, Infinity, '800시간 이상']]
    .map(([lo, hi, label]) => { const a = W.filter(c => { const h = hoursOf(c); return h != null && h >= lo && h <= hi; }).map(c => c.emplRate); return { label, n: a.length, avg: avg(a) }; })
    .filter(b => b.n >= 20);

  // ② 분야별 분포 (분야 간 격차 vs 분야 안 격차)
  // 'etc'(기타)는 제외 — 분류 실패분을 모은 버킷이라 해석이 불가능하고, /c/etc 페이지도 생성되지 않는다(링크 404 방지).
  const realCats = M.cats.filter(c => c.slug !== 'etc');
  const catRows = realCats.map(cat => {
    const a = W.filter(c => c.cat === cat.slug).map(c => c.emplRate);
    if (a.length < 30) return null;
    return { slug: cat.slug, name: cat.name, n: a.length, avg: avg(a), p10: pct(a, 0.1), p90: pct(a, 0.9) };
  }).filter(Boolean).map(r => ({ ...r, spread: r.p90 - r.p10 })).sort((x, y) => y.avg - x.avg);

  // ③ 시도별 (표본 100건 이상만)
  const sidoMap = {};
  for (const c of W) if (c.sido) (sidoMap[c.sido] = sidoMap[c.sido] || []).push(c.emplRate);
  const sidoRows = Object.entries(sidoMap).filter(([, a]) => a.length >= 100)
    .map(([sido, a]) => ({ sido, n: a.length, avg: avg(a) })).sort((x, y) => y.avg - x.avg);
  const seoulRank = sidoRows.findIndex(r => r.sido === '서울') + 1;
  const seoul = sidoRows.find(r => r.sido === '서울');

  // ④ 교란검증 A — 같은 훈련시간대(100시간 미만) 안에서 자부담 비용 차이
  const shortB = W.filter(c => { const h = hoursOf(c); return h != null && h < 100 && c.costWon != null; });
  const costCheap = shortB.filter(c => c.costWon < 500000).map(c => c.emplRate);
  const costPricey = shortB.filter(c => c.costWon >= 1000000).map(c => c.emplRate);

  // ⑤ 교란검증 B — 같은 분야 안에서 단기(200시간 미만) vs 장기(500시간 이상)
  const durByCat = realCats.map(cat => {
    const a = W.filter(c => c.cat === cat.slug);
    const s = a.filter(c => { const h = hoursOf(c); return h != null && h < 200; }).map(c => c.emplRate);
    const l = a.filter(c => { const h = hoursOf(c); return h != null && h >= 500; }).map(c => c.emplRate);
    if (s.length < 20 || l.length < 20) return null;
    return { name: cat.name, slug: cat.slug, nS: s.length, avgS: avg(s), nL: l.length, avgL: avg(l), gap: avg(l) - avg(s) };
  }).filter(Boolean).sort((x, y) => y.gap - x.gap);

  // ⑥ 교란검증 C — 같은 분야 안에서 서울 vs 비서울
  const seoulByCat = realCats.map(cat => {
    const a = W.filter(c => c.cat === cat.slug);
    const s = a.filter(c => c.sido === '서울').map(c => c.emplRate);
    const o = a.filter(c => c.sido && c.sido !== '서울').map(c => c.emplRate);
    if (s.length < 30 || o.length < 30) return null;
    return { name: cat.name, slug: cat.slug, nS: s.length, avgS: avg(s), nO: o.length, avgO: avg(o), gap: avg(s) - avg(o) };
  }).filter(Boolean).sort((x, y) => x.gap - y.gap);

  // ⑦ 장기과정 비중 (서울이 구성상 유리한데도 낮은지 확인용)
  const longShare = list => { const a = list.filter(c => hoursOf(c) != null); return a.length ? a.filter(c => hoursOf(c) >= 200).length / a.length * 100 : null; };

  // ⑧ 비용 구간별 전체 평균 (교란검증 전 "비싼 게 좋아 보이는" 착시의 크기)
  const costBandAll = lo => { const a = W.filter(c => c.costWon != null && (lo ? c.costWon >= 1000000 : c.costWon < 1000000)).map(c => c.emplRate); return { n: a.length, avg: avg(a) }; };
  const costHiAll = costBandAll(true), costLoAll = costBandAll(false);

  // ⑨ 분야 간 격차 vs 분야 안 격차 — 분야 안이 더 큰 분야가 몇 개인지
  const betweenGap = catRows.length ? catRows[0].avg - catRows[catRows.length - 1].avg : 0;
  const widerInside = catRows.filter(r => r.spread > betweenGap).length;

  return {
    W, avg, r1, hoursOf, catName, hourBins, catRows, sidoRows, seoulRank, seoul, durByCat, seoulByCat,
    eun, gwa, betweenGap, widerInside,
    costHiAll, costLoAll, costIllusion: costHiAll.avg - costLoAll.avg,
    total: W.length,
    costCheap: { n: costCheap.length, avg: avg(costCheap) },
    costPricey: { n: costPricey.length, avg: avg(costPricey) },
    longShareSeoul: longShare(W.filter(c => c.sido === '서울')),
    longShareAll: longShare(W),
    rate100: W.filter(c => c.emplRate >= 100).length,
    rate90: W.filter(c => c.emplRate >= 90).length,
  };
}

